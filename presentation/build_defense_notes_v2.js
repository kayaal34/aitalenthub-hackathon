function slideHeading(s) {
  return new Paragraph({
    spacing: { before: 260, after: 40 },
    children: [
      new TextRun({ text: `Слайд ${s.n}. ${s.title}`, bold: true, size: 26, color: ACCENT }),
      new TextRun({ text: `   — ${s.cue}`, italics: true, size: 19, color: GRAY }),
    ],
  });
}
function bodyPara(text) {
  return new Paragraph({
    spacing: { after: 120, line: 300 },
    children: [new TextRun({ text, size: 23, color: "1A1A1A" })],
  });
}

const children = [
  new Paragraph({
    heading: HeadingLevel.TITLE,
    spacing: { after: 80 },
    children: [new TextRun({ text: "Защита — что говорить", bold: true })],
  }),
  new Paragraph({
    spacing: { after: 320 },
    children: [new TextRun({
      text: "По одному короткому абзацу на слайд (≈15–20 секунд). Говорите своими словами. Места в [квадратных скобках] замените сами.",
      italics: true, color: GRAY, size: 20,
    })],
  }),
  new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun("Речь по слайдам")] }),
];

slides.forEach((s) => {
  children.push(slideHeading(s));
  children.push(bodyPara(s.text));
});

children.push(new Paragraph({
  heading: HeadingLevel.HEADING_1,
  pageBreakBefore: true,
  children: [new TextRun("Короткие ответы на вопросы")],
}));

qa.forEach((item, i) => {
  children.push(new Paragraph({
    spacing: { before: 200, after: 40 },
    children: [new TextRun({ text: `${i + 1}. ${item.q}`, bold: true, size: 23, color: ACCENT })],
  }));
  children.push(new Paragraph({
    spacing: { after: 120, line: 300 },
    children: [new TextRun({ text: item.a, size: 23, color: "1A1A1A" })],
  }));
  children.push(new Paragraph({
    spacing: { after: 40 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 4, color: "E1E7EF" } },
    children: [],
  }));
});

Packer.toBuffer(new Document({ sections: [{ properties: {}, children }] })).then((buf) => {
  fs.writeFileSync(OUT, buf);
  console.log("Готово:", OUT);
});
