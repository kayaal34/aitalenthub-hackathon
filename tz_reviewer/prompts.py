"""Промпты для LLM-ревью ТЗ."""

from __future__ import annotations

from .knowledge import Knowledge
from .models import Section
from .rubric import RUBRIC_KEYS, rubric_prompt_block

SYSTEM_PROMPT = """\
Ты — старший инженер данных и ревьюер технических заданий (ТЗ) на разработку
новых потоков и витрин данных в продукте NET (поставка данных из источников
радиосети).

Твоя роль — предварительное ревью ТЗ до передачи задачи в разработку. Нужно
найти места, которые разработчик поймёт неоднозначно, где не хватает
информации для реализации, где разделы противоречат друг другу.

Жёсткие правила:
- Ты НЕ переписываешь ТЗ и НЕ выносишь итоговое решение о готовности документа —
  это делает аналитик. Ты только показываешь проблемные места.
- Каждое замечание должно быть привязано к конкретному фрагменту ЭТОГО ТЗ
  (дословная цитата). Без общих советов «добавьте больше деталей».
- Если место в ТЗ описано корректно — не выдумывай к нему замечаний.
- Пиши по-русски, по делу, в терминах разработки данных.
- Формулируй так, чтобы аналитик за 10 секунд понял: где место, что не так,
  что дописать, какой вопрос задать.
"""

_OUTPUT_CONTRACT = """\
Верни СТРОГО один JSON-объект и больше ничего (без markdown-обёртки, без ```):

{{
  "document_title": "краткое название ТЗ из текста",
  "summary": "3–6 предложений: общий результат проверки — можно ли передавать в \
разработку, какие темы вызывают больше всего вопросов, на что аналитику \
обратить внимание в первую очередь",
  "findings": [
    {{
      "category": "<одно из: {categories}>",
      "severity": "blocker | major | minor",
      "section": "название или номер раздела ТЗ, к которому относится замечание",
      "quote": "дословный фрагмент из ТЗ (до 300 символов) — ОДНА конкретная строка/ячейка/предложение, к которому претензия. Не склеивай в quote несколько строк таблицы (например заголовок + разделитель + данные) — бери только ту одну строку, которая содержит проблему",
      "issue": "что именно непонятно или отсутствует",
      "impact": "почему это важно для разработки — что пойдёт не так без уточнения",
      "recommendation": "что конкретно уточнить или добавить в ТЗ",
      "question_for_analyst": "один конкретный вопрос, который стоит задать аналитику"
    }}
  ]
}}

Критичность:
- blocker — без этого нельзя начинать разработку либо высок риск сделать не то
  (не определён источник, ключ, гранулярность, стратегия загрузки, историчность).
- major — реализуемо, но вероятны переделка и повторное согласование
  (расплывчатая логика, типы, фильтры, соединения, обработка NULL).
- minor — стоит поправить для качества (термины, примеры, объёмы, оформление).

Ориентир: 5–20 замечаний. Сначала важное. Не дублируй одно и то же замечание.
"""


def output_contract() -> str:
    return _OUTPUT_CONTRACT.format(categories=", ".join(RUBRIC_KEYS))


def _trim(text: str, limit: int) -> str:
    text = (text or "").strip()
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + "\n[…фрагмент сокращён…]"


def build_user_prompt(
    document_text: str,
    sections: list[Section],
    knowledge: Knowledge,
    *,
    sources_note: str = "",
    doc_char_budget: int = 24000,
) -> str:
    parts: list[str] = []

    parts.append(
        "Ниже — материалы для ревью: (1) ориентиры (шаблон, чек-лист, типовые "
        "корректировки разработчиков, примеры), затем (2) сам текст ТЗ. Используй "
        "ориентиры как систему координат, но оценивай именно текст ТЗ."
    )

    parts.append("\n===== РУБРИКА РЕВЬЮ (категории и на что смотреть) =====\n" + rubric_prompt_block())

    if knowledge.template:
        parts.append("\n===== ШАБЛОН ТЗ (ожидаемая структура) =====\n" + _trim(knowledge.template, 6000))
    if knowledge.checklist:
        parts.append("\n===== ЧЕК-ЛИСT (расширенный) =====\n" + _trim(knowledge.checklist, 6000))
    if knowledge.corrections:
        parts.append(
            "\n===== ТИПОВЫЕ КОРРЕКТИРОВКИ РАЗРАБОТЧИКОВ (что чаще всего просят уточнить) =====\n"
            + _trim(knowledge.corrections, 6000)
        )
    few_shot = knowledge.few_shot_prompt_block()
    if few_shot:
        parts.append("\n===== ПРИМЕРЫ ЗАМЕЧАНИЙ (образец формы и уровня конкретики) =====\n" + few_shot)

    if sources_note:
        parts.append("\n===== ЗАМЕЧАНИЕ АНАЛИТИКА К КОНТЕКСТУ =====\n" + sources_note.strip())

    outline = "\n".join(f"- {s.heading}" for s in sections)
    parts.append("\n===== СТРУКТУРА ПРОВЕРЯЕМОГО ТЗ =====\n" + outline)

    parts.append("\n===== ТЕКСТ ТЗ ДЛЯ РЕВЬЮ =====\n" + _trim(document_text, doc_char_budget))

    parts.append("\n===== ФОРМАТ ОТВЕТА =====\n" + output_contract())

    return "\n".join(parts)


