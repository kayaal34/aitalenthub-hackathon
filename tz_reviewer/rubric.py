RUBRIC_BY_KEY: dict[str, RubricItem] = {item.key: item for item in RUBRIC}
RUBRIC_KEYS: tuple[str, ...] = tuple(item.key for item in RUBRIC)


def rubric_prompt_block() -> str:
    """Компактное представление рубрики для системного промпта LLM."""

    lines: list[str] = []
    for item in RUBRIC:
        lines.append(f"- {item.key} — {item.title} (обычно: {item.typical_severity}).")
        lines.append(f"  На что смотреть: {item.focus}")
    return "\n".join(lines)


def rubric_markdown() -> str:
    """Человекочитаемый чек-лист (используется в knowledge/checklist.md и в доках)."""

    blocks: list[str] = ["# Чек-лист предварительного ревью ТЗ\n"]
    for i, item in enumerate(RUBRIC, 1):
        blocks.append(f"## {i}. {item.title} (`{item.key}`)\n")
        blocks.append(f"**Типовая критичность:** {item.typical_severity}\n")
        blocks.append(f"{item.focus}\n")
        blocks.append("Контрольные вопросы:\n")
        blocks.extend(f"- {q}" for q in item.questions)
        blocks.append("")
    return "\n".join(blocks)
